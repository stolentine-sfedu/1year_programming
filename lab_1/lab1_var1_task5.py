"""
Ввести количество пассажиров passengers. 
Вывести, сколько полных автобусов по 40 человек и сколько останется, используя // и %.
"""

passengers = int(input("Введите количество пассажиров: "))

print(f"Количество полных автобусов по 40 человек: {passengers // 40}")
print(f"Количество оставшихся на пероне: {passengers % 40}")

